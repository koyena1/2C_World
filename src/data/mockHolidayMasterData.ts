export interface HolidayPolicy {
  mandatoryCount: number;      // Fixed observed days
  optionalAvailable: number;   // Total available optional days
  choicePool: number;          // Max number employee can choose
  totalPooled: number;         // mandatoryCount + choicePool
}

export interface HolidayCalendar {
  id: string;
  name: string;
  region: string;
  year: number;
  status: 'Draft' | 'Published' | 'Active';
  policy: HolidayPolicy;
  assignedEmployeesCount: number;
  createdHolidayCount: number;
  intakeAnalytics: {
    selected: number;
    notSelected: number;
    rate: number;
  };
  lastUpdated: string;
  description: string;
}

export interface HolidayMasterItem {
  id: string;
  calendarId: string;
  name: string;
  date: string;
  dayOfWeek: string;
  type: 'Mandatory' | 'Optional';
  status: 'Active' | 'Inactive';
  description?: string;
}

export interface HolidayEmployeeRecord {
  employeeId: string;
  name: string;
  email: string;
  department: string;
  grade: string;
  client: string;
  location: string;
  joiningDate: string;
  status: 'Joined' | 'Yet to Join' | 'Re-Joined' | 'Offer Not Rolled Out';
  calendarId: string;
  calendarName: string;
  selectionStatus: 'Selected' | 'Pending' | 'Not Linked';
  selectedHolidays: string[];
}

